// Maintainer-only build. End users open index.html and paste the generated Office Script.
import {readFileSync,writeFileSync,readdirSync,statSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {join,relative,dirname} from 'node:path';
import {stripTypeScriptTypes} from 'node:module';
import {createHash} from 'node:crypto';
const root=fileURLToPath(new URL('../',import.meta.url));
const read=p=>readFileSync(join(root,p),'utf8');
let publisher=read('scripts/UpdateReadinessWorkbook.ts').replace('function main(workbook: ExcelScript.Workbook, payloadJson: string): string {','function publishReadiness(workbook: ExcelScript.Workbook, payloadJson: string, dryRun: boolean): string {');
publisher=publisher.replace('for (const plan of plans) {',"if (dryRun) return JSON.stringify({status:'validated_only'});\n  for (const plan of plans) {")
 .replace('r.map(safe)','r.map(value=>safe(value))').replace('p.sheets.forEach(prepare)','p.sheets.forEach(view=>prepare(view))');
const runtime=read('setup/runtime.ts').replaceAll('.sort(sortRecords)','.sort((a,b)=>sortRecords(a,b))');
const office='// GENERATED by setup/build.mjs. Edit setup sources, not this bundle.\n'+runtime+'\n'+publisher+'\n'+read('setup/office-entry.ts');
writeFileSync(join(root,'scripts/RunReadinessNoPython.ts'),office);
writeFileSync(join(root,'setup/runtime.js'),stripTypeScriptTypes(runtime));
const files={};
function walk(dir){for(const name of readdirSync(join(root,dir)).sort()){const path=join(dir,name),abs=join(root,path);if(statSync(abs).isDirectory())walk(path);else{
 const rel=path.replaceAll('\\','/');
 if(/\.(md|json|csv|yaml|yml|xlsx|ts|vtt|png)$/.test(rel))files[rel]={encoding:/\.(xlsx|png)$/.test(rel)?'base64':'utf8',content:/\.(xlsx|png)$/.test(rel)?readFileSync(abs).toString('base64'):readFileSync(abs,'utf8')};
}}}
for(const d of ['agents','skills','prompts','templates','config','automation','docs','scripts','examples','assets'])walk(d);
files['LICENSE']={encoding:'utf8',content:read('LICENSE')};
files['README.md']={encoding:'utf8',content:'# Your no-Python setup kit\n\nStart with docs/NO-PYTHON-START-HERE.md. This kit preserves the canonical operational instructions. Connections remain unverified until tested in your tenant.\n'};
const manifest=Object.entries(files).map(([path,v])=>({path,sha256:createHash('sha256').update(v.encoding==='base64'?Buffer.from(v.content,'base64'):v.content).digest('hex')}));
writeFileSync(join(root,'setup/bundle-manifest.json'),JSON.stringify(manifest,null,2)+'\n');
const embedded=JSON.stringify(files).replaceAll('<','\\u003c');
const html=read('setup/page.html').replace('/* RUNTIME */',stripTypeScriptTypes(runtime)).replace('/* BUNDLE */','const packageFiles='+embedded+';').replace('/* APP */',read('setup/wizard.js'));
writeFileSync(join(root,'setup/index.html'),html);
console.log(JSON.stringify({files:manifest.length,officeBytes:office.length,wizardBytes:html.length}));
